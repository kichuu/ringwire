use std::io::Write;

/// Content types indexed by the `type` code the JS side sends.
const CONTENT_TYPES: [&str; 4] = [
    "application/json",
    "text/plain; charset=utf-8",
    "text/html; charset=utf-8",
    "application/octet-stream",
];

fn reason(status: u16) -> &'static str {
    match status {
        100 => "Continue",
        101 => "Switching Protocols",
        200 => "OK",
        201 => "Created",
        202 => "Accepted",
        204 => "No Content",
        206 => "Partial Content",
        301 => "Moved Permanently",
        302 => "Found",
        303 => "See Other",
        304 => "Not Modified",
        307 => "Temporary Redirect",
        308 => "Permanent Redirect",
        400 => "Bad Request",
        401 => "Unauthorized",
        403 => "Forbidden",
        404 => "Not Found",
        405 => "Method Not Allowed",
        406 => "Not Acceptable",
        408 => "Request Timeout",
        409 => "Conflict",
        410 => "Gone",
        411 => "Length Required",
        412 => "Precondition Failed",
        413 => "Payload Too Large",
        415 => "Unsupported Media Type",
        422 => "Unprocessable Entity",
        429 => "Too Many Requests",
        431 => "Request Header Fields Too Large",
        500 => "Internal Server Error",
        501 => "Not Implemented",
        502 => "Bad Gateway",
        503 => "Service Unavailable",
        504 => "Gateway Timeout",
        _ => "Unknown",
    }
}

/// Headers the server manages itself; user-supplied copies are dropped.
fn is_managed(name: &str) -> bool {
    ["content-length", "transfer-encoding", "connection", "date"]
        .iter()
        .any(|m| name.eq_ignore_ascii_case(m))
}

fn is_token(name: &str) -> bool {
    !name.is_empty()
        && name
            .bytes()
            .all(|b| b.is_ascii_alphanumeric() || b"!#$%&'*+-.^_`|~".contains(&b))
}

/// Header names must be tokens and values must not contain CR, LF or NUL,
/// otherwise a handler could inject extra headers or split the response.
fn headers_valid(headers: &[String]) -> bool {
    headers.len().is_multiple_of(2)
        && headers.chunks(2).all(|kv| {
            is_token(&kv[0]) && !kv[1].bytes().any(|b| b == b'\r' || b == b'\n' || b == 0)
        })
}

/// Serialize a complete HTTP/1.1 response into `out`.
///
/// `headers` is a flat `[name, value, ...]` list. Invalid headers turn the
/// response into a 500. For HEAD requests the body is measured but not sent.
pub fn encode(
    out: &mut Vec<u8>,
    status: u16,
    ctype: u32,
    headers: Option<&[String]>,
    body: &[u8],
    head: bool,
    date: &str,
) {
    if let Some(h) = headers {
        if !headers_valid(h) {
            eprintln!(
                "ringwire: invalid response header (bad name or CR/LF in value); sending 500"
            );
            return encode(out, 500, 1, None, b"Internal Server Error", head, date);
        }
    }
    out.reserve(body.len() + 160);
    let _ = write!(
        out,
        "HTTP/1.1 {} {}\r\ndate: {}\r\n",
        status,
        reason(status),
        date
    );

    let mut has_ctype = false;
    if let Some(h) = headers {
        for kv in h.chunks(2) {
            if is_managed(&kv[0]) {
                continue;
            }
            has_ctype |= kv[0].eq_ignore_ascii_case("content-type");
            let _ = write!(out, "{}: {}\r\n", kv[0], kv[1]);
        }
    }

    // 1xx/204/304 must not carry a body or Content-Length.
    if status == 204 || status == 304 || status < 200 {
        out.extend_from_slice(b"\r\n");
        return;
    }
    if !has_ctype {
        let ct = CONTENT_TYPES
            .get(ctype as usize)
            .copied()
            .unwrap_or(CONTENT_TYPES[3]);
        let _ = write!(out, "content-type: {}\r\n", ct);
    }
    let _ = write!(out, "content-length: {}\r\n\r\n", body.len());
    if !head {
        out.extend_from_slice(body);
    }
}

/// Plain-text error response generated by the server itself (bad requests,
/// timeouts). Always closes the connection.
pub fn error(status: u16, date: &str) -> Vec<u8> {
    let msg = reason(status);
    let mut out = Vec::with_capacity(160);
    let _ = write!(
        out,
        "HTTP/1.1 {} {}\r\ndate: {}\r\ncontent-type: text/plain; charset=utf-8\r\ncontent-length: {}\r\nconnection: close\r\n\r\n{}",
        status,
        msg,
        date,
        msg.len(),
        msg
    );
    out
}

#[cfg(test)]
mod tests {
    use super::*;

    fn s(v: &[&str]) -> Vec<String> {
        v.iter().map(|x| x.to_string()).collect()
    }

    #[test]
    fn rejects_header_injection() {
        assert!(!headers_valid(&s(&["x-a", "ok\r\nset-cookie: evil=1"])));
        assert!(!headers_valid(&s(&["bad name", "v"])));
        assert!(!headers_valid(&s(&["x-a"])));
        assert!(headers_valid(&s(&["x-a", "fine value"])));
    }

    #[test]
    fn invalid_headers_become_500() {
        let mut out = Vec::new();
        encode(
            &mut out,
            200,
            0,
            Some(&s(&["x", "a\nb"])),
            b"{}",
            false,
            "d",
        );
        assert!(out.starts_with(b"HTTP/1.1 500"));
    }

    #[test]
    fn head_keeps_length_drops_body() {
        let mut out = Vec::new();
        encode(&mut out, 200, 1, None, b"hello", true, "d");
        let text = String::from_utf8(out).unwrap();
        assert!(text.contains("content-length: 5\r\n"));
        assert!(text.ends_with("\r\n\r\n"));
    }

    #[test]
    fn user_content_type_wins_and_managed_headers_dropped() {
        let mut out = Vec::new();
        let h = s(&[
            "Content-Type",
            "image/png",
            "Content-Length",
            "999",
            "x-id",
            "7",
        ]);
        encode(&mut out, 200, 0, Some(&h), b"abc", false, "d");
        let text = String::from_utf8(out).unwrap();
        assert!(text.contains("Content-Type: image/png\r\n"));
        assert!(!text.contains("application/json"));
        assert!(!text.contains("999"));
        assert!(text.contains("content-length: 3\r\n"));
        assert!(text.contains("x-id: 7\r\n"));
    }
}
